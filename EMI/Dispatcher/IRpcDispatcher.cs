using System;

namespace EMI
{
    /// <summary>
    /// Стратегия исполнения входящих RPC-вызовов: определяет, НА КАКОМ потоке и
    /// в каком порядке выполняются пользовательские обработчики.
    /// <para>
    /// EMI по умолчанию исполняет RPC на пуле потоков (<see cref="ThreadPoolDispatcher"/>).
    /// Для движков вроде Unity, где API не потокобезопасен и вызовы должны идти в main-потоке,
    /// назначьте <see cref="PumpDispatcher"/> или <see cref="SynchronizationContextDispatcher"/>.
    /// Реализовав интерфейс самостоятельно, можно задать любую модель: ограниченный
    /// параллелизм, приоритетную очередь, шардирование по клиенту и т.п.
    /// </para>
    /// </summary>
    /// <remarks>
    /// Контракт для реализаций:
    /// <list type="bullet">
    /// <item>Каждый переданный <paramref name="call"/> должен быть исполнен ровно один раз.</item>
    /// <item><see cref="Post"/> вызывается с сетевого потока приёма — НЕ блокируйте его надолго,
    /// иначе тормозится чтение пакетов. Кладите вызов в очередь и возвращайте управление.</item>
    /// <item>Исключения внутри <paramref name="call"/> перехватываются и логируются самим EMI —
    /// реализации оборачивать в try/catch не обязаны, но и не должны «глотать» вызов.</item>
    /// </list>
    /// </remarks>
    public interface IRpcDispatcher
    {
        /// <summary>
        /// Принять готовый к исполнению RPC-вызов. Реализация решает, где и когда его выполнить.
        /// </summary>
        /// <param name="call">замыкание, выполняющее распаковку аргументов и пользовательский обработчик</param>
        void Post(Action call);
    }
}
